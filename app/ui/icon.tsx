export type IconName = keyof typeof paths;

const sources = new Map<IconName, string>();
const source = (name: IconName) => {
  let src = sources.get(name);
  if (!src) {
    const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="24" height="24" viewBox="0 0 24 24" fill="none" stroke="#000" stroke-width="1.75" stroke-linecap="round" stroke-linejoin="round">${paths[name]}</svg>`;
    src = `data:image/svg+xml,${encodeURIComponent(svg)}`;
    sources.set(name, src);
  }
  return src;
};

/** Any theme color: `foreground`, `primary`, `default-500`, `danger-600` … */
export type IconTone = ColorRole | "unread" | "flag";

export type IconSize = "sm" | "md" | "lg";
// M3 icon sizes: 24pt, 18pt beside small text (chips, list metadata), 32pt for empty states.
const iconPx = (size: IconSize = "md") => ({ sm: 18, md: 24, lg: 32 })[size];

/** A brand's mark (an SVG asset) in its own colors, at an icon's size. */
export function BrandMark(props: { src: ImageAsset; size?: IconSize }) {
  return (
    <Image
      src={props.src}
      accessibilityElementsHidden
      style={{ width: iconPx(props.size), height: iconPx(props.size), pointerEvents: "none" }}
    />
  );
}

/** A line icon tinted with a theme color; `class` adds state tints (`group-hover:tint-…`).
 * Decorative unless the control around it names it. */
export function Icon(props: { name: IconName; tone?: IconTone; size?: IconSize; class?: string }) {
  return (
    <Image
      src={source(props.name)}
      accessibilityElementsHidden
      class={`${props.tone ? `tint-${props.tone}` : props.class ? "" : "tint-on-surface"} ${props.class ?? ""}`}
      style={{ width: iconPx(props.size), height: iconPx(props.size), pointerEvents: "none" }}
    />
  );
}
